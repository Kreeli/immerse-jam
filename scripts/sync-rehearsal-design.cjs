// Reuse PR #6's actual CSS. Keep the accepted prototype unchanged and namespace
// its classes so its component rules cannot collide with legacy feature views.
const fs = require('node:fs');
const crypto = require('node:crypto');
const source = 'docs/design/prototype.html';
const html = fs.readFileSync(source, 'utf8');
const blocks = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((match) => match[1]);
if (blocks.length !== 4)
  throw new Error('Review the prototype stylesheet structure before syncing.');
let css = blocks.join('\n');
const base = css.indexOf('/* ================= base');
const controls = css.indexOf('/* ================= shared controls');
if (base < 0 || controls <= base) throw new Error('Prototype stylesheet sections changed.');
css = css.slice(0, base) + css.slice(controls); // omit global resets and prototype toolbar
css = css
  .replace(/\.([A-Za-z_][\w-]*)/g, '.nr-$1')
  .replace(/\[data-accent=(["'])ocean\1\]/g, "[data-accent='blue']")
  .replace(/\[data-accent=(["'])pine\1\]/g, "[data-accent='green']")
  .replace(/\[data-accent=(["'])violet\1\]/g, "[data-accent='purple']");
const hash = crypto.createHash('sha256').update(html).digest('hex');
const output =
  `/* Derived directly from ${source}, PR #6 by wweiyi2004.\n * Source SHA-256: ${hash}\n * Generated by scripts/sync-rehearsal-design.cjs. Class namespace and legacy\n * accent aliases are the only transformations of the component CSS.\n * Product behavior lives in React; demo audio, data and handlers are not used.\n */\n` +
  css;
const prettier = require('prettier');
prettier
  .resolveConfig('src/styles/rehearsal-design.css')
  .then((config) => prettier.format(output, { ...config, parser: 'css' }))
  .then((formatted) => fs.writeFileSync('src/styles/rehearsal-design.css', formatted));
